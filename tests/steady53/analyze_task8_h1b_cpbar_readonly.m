end

function eta = turbineEfficiency(tablePayload, massFlow, speed)
required = ["bp_mf" "bp_speed" "table_eff"];
if ~isstruct(tablePayload) || ~all(isfield(tablePayload, required))
    invalidInput("Turbine efficiency table fields are missing.");
end
bp_mf = double(tablePayload.bp_mf(:));
bp_speed = double(tablePayload.bp_speed(:));
table_eff = double(tablePayload.table_eff);
if numel(bp_mf) < 2 || numel(bp_speed) < 2 || ...
        any(~isfinite(bp_mf)) || any(~isfinite(bp_speed)) || ...
        any(diff(bp_mf) <= 0) || any(diff(bp_speed) <= 0) || ...
        ~isequal(size(table_eff), [numel(bp_mf) numel(bp_speed)]) || ...
        any(~isfinite(table_eff), "all") || ...
        massFlow < bp_mf(1) || massFlow > bp_mf(end) || ...
        speed < bp_speed(1) || speed > bp_speed(end)
    invalidInput("The turbine efficiency lookup contract is invalid.");
end
eta = interpn(bp_mf, bp_speed, table_eff, massFlow, speed, "linear");
if ~finiteRealScalar(eta) || eta <= 0 || eta >= 1
    invalidInput("The interpolated turbine efficiency is invalid.");
end
end

function validatePointProperty(cp, gamma, rho)
if ~finiteRealScalar(cp) || ~finiteRealScalar(gamma) || ...
        ~finiteRealScalar(rho) || cp <= 0 || gamma <= 1 || ...
        cp/gamma <= 0 || rho <= 0
    error("steady53:H1bBaselineMismatch", ...
        "The formal point property is nonphysical.");
end
end

