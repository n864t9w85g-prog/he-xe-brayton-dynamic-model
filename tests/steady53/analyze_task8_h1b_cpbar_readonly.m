error("steady53:H1bInvalidOptions", "%s", message);
end

function [hashes, archiveCommit] = validateProtectedIdentities( ...
        config, h1aCsvHash, h1aTxtHash)
hashes = currentProtectedHashes(config);
hashes.h1aCsvSha256 = h1aCsvHash;
hashes.h1aTxtSha256 = h1aTxtHash;
checks = [ ...
    hashes.inputMatSha256 == lower(config.expectedInputSha256)
    hashes.modelSha256 == lower(config.expectedModelSha256)
    hashes.formalPropertySha256 == ...
        lower(config.expectedFormalPropertySha256)
    hashes.turbineTableSha256 == lower(config.expectedTurbineTableSha256)
    hashes.schemeAHelperSha256 == lower(config.expectedSchemeAHelperSha256)
    hashes.h2aCsvSha256 == lower(config.expectedH2aCsvSha256)
    hashes.h2aTxtSha256 == lower(config.expectedH2aTxtSha256)];
if ~all(checks)
    error("steady53:H1bProtectedHashMismatch", ...
        "A protected H1b dependency hash does not match its fixed identity.");
end
archiveCommit = resolveArchiveCommit(config.archiveRef);
if archiveCommit ~= lower(config.expectedArchiveCommit)
    error("steady53:H1bProtectedHashMismatch", ...
        "The restart archive ref no longer resolves to its fixed commit.");
end
end

