function analysis = analyze_task8_h1b_cpbar_readonly(options)
%ANALYZE_TASK8_H1B_CPBar_READONLY Fixed-evidence offline H1b experiment.
%   Scheme A remains confined to the approved H1a-S2 phi result. H1b uses
%   formal HeXe_property_simulink values for three explicit cp-bar paths.

root = fileparts(fileparts(fileparts(mfilename("fullpath"))));
config = defaultConfig(root);
if nargin > 0
    config = applyOptions(config, options);
end
validateConfig(config);

% H1a evidence identity is the first gate and has its own failure class.
h1aCsvHash = sha256File(config.h1aCsvPath);
h1aTxtHash = sha256File(config.h1aTxtPath);
if h1aCsvHash ~= lower(config.expectedH1aCsvSha256) || ...
        h1aTxtHash ~= lower(config.expectedH1aTxtSha256)
    error("steady53:H1bH1aEvidenceHashMismatch", ...
        "Approved H1a-S2 evidence hash mismatch.");
end

[hashes, archiveCommit] = validateProtectedIdentities(config, ...
    h1aCsvHash, h1aTxtHash);
h1aEvidence = validateH1aEvidence(config, hashes);

originalPath = path;
originalWarnings = warning;
loadedBefore = loadedBlockDiagrams();
environmentCleanup = onCleanup(@() restoreEnvironment( ...
    originalPath, originalWarnings));
addpath(root, "-begin");
addpath(fullfile(root, "tests", "steady53"), "-begin");
clear("HeXe_property_simulink");

payload = load(config.inputMat, "result", "report", "spec");
inputs = validateAndExtractPayload(payload, hashes.modelSha256);
tablePayload = load(config.turbineTableMat, ...
    "bp_mf", "bp_speed", "table_eff");
inputs.eta = turbineEfficiency(tablePayload, ...
    inputs.lookupMassFlow_kg_s, inputs.lookupSpeed_rpm);
inputs.phiBar = h1aEvidence.phiBar;
inputs.T2s_K = h1aEvidence.T2s_K;

clear("HeXe_property_simulink");
[pointCp1, pointGamma1, pointRho1] = config.propertyFunction( ...
    inputs.T1_K, inputs.P1_Pa);
[pointCp2s, pointGamma2s, pointRho2s] = config.propertyFunction( ...
    h1aEvidence.pointCp2SourceT_K, inputs.P2_Pa);
validatePointProperty(pointCp1, pointGamma1, pointRho1);
validatePointProperty(pointCp2s, pointGamma2s, pointRho2s);
pointT2_K = inputs.T1_K-inputs.eta*(pointCp2s/pointCp1)* ...
    (inputs.T1_K-inputs.T2s_K);
pointResidual_K = pointT2_K-h1aEvidence.T2_K;
clear("HeXe_property_simulink");
if ~finiteRealScalar(pointT2_K) || abs(pointResidual_K) > 1e-9
    error("steady53:H1bBaselineMismatch", ...
        "The formal point-cp equation does not reproduce H1a-S2 within 1e-9 K.");
end

solverInputs = struct("T1_K", inputs.T1_K, ...
    "P1_Pa", inputs.P1_Pa, "P2_Pa", inputs.P2_Pa, ...
    "T2s_K", inputs.T2s_K, "eta", inputs.eta);
candidateCells = cell(1, numel(config.pathVariants));
for index = 1:numel(config.pathVariants)
    candidate = h1b_cpbar_candidate_readonly(solverInputs, ...
        config.pathVariants(index), config.propertyFunction, config.numerics);
    candidate.deltaT2FromH1a_K = candidate.T2_K-h1aEvidence.T2_K;
    candidate.remainingTargetError_K = inputs.targetT2_K-candidate.T2_K;
    candidate.explainedFractionOfH1aGap = ...
        candidate.deltaT2FromH1a_K/(inputs.targetT2_K-h1aEvidence.T2_K);
    candidate.targetDirectionMatched = ...
        sign(candidate.deltaT2FromH1a_K) == ...
        sign(inputs.targetT2_K-h1aEvidence.T2_K);
    candidate.h1bNumericallySufficient = ...
        candidate.targetDirectionMatched && ...
        abs(candidate.deltaT2FromH1a_K) >= ...
        abs(inputs.targetT2_K-h1aEvidence.T2_K);
    candidateCells{index} = candidate;
end
candidates = [candidateCells{:}];
clear("HeXe_property_simulink");

scope = struct( ...
    "h1aPhiPropertyVariant", "schemeA", ...
    "h1bCpbarPropertyVariant", "formalHeXeProperty", ...
    "T2sHeldFixed", true, ...
    "etaHeldFixed", true, ...
    "onlyPointCpReplacedByPathCpbar", true);
evidenceTable = makeEvidenceTable(config, hashes, archiveCommit, ...
    inputs, h1aEvidence, pointCp1, pointCp2s, candidates, scope);
summaryText = makeSummary(config, hashes, archiveCommit, inputs, ...
    h1aEvidence, pointCp1, pointGamma1, pointRho1, pointCp2s, ...
    pointGamma2s, pointRho2s, pointT2_K, pointResidual_K, ...
    candidates, scope);

loadedAfter = loadedBlockDiagrams();
if ~isequal(loadedAfter, loadedBefore)
    error("steady53:H1bEnvironmentChanged", ...
        "Loaded block diagrams changed during the read-only analyzer.");
end
postHashes = currentProtectedHashes(config);
if ~isequal(postHashes, hashes)
    error("steady53:H1bReadOnlyViolation", ...
        "A protected dependency changed during the read-only analyzer.");
end

[csvHash, summaryHash] = publishEvidence(config.outputDir, ...
    evidenceTable, summaryText, config.outputFailureHook);
csvPath = string(fullfile(config.outputDir, ...
    "h1b_cpbar_sensitivity.csv"));
summaryPath = string(fullfile(config.outputDir, ...
    "h1b_cpbar_summary.txt"));

clear("HeXe_property_simulink");
path(originalPath);
warning(originalWarnings);
clear environmentCleanup

analysis = struct( ...
    "runId", config.runId, ...
    "inputs", inputs, ...
    "scope", scope, ...
    "hashes", hashes, ...
    "archiveRef", config.archiveRef, ...
    "archiveCommit", archiveCommit, ...
    "h1aCandidateT2_K", h1aEvidence.T2_K, ...
    "h1aPointCpRecomputedT2_K", pointT2_K, ...
    "h1aPointCpReproductionResidual_K", pointResidual_K, ...
    "pointCp1_J_kgK", pointCp1, ...
    "pointCp2s_J_kgK", pointCp2s, ...
    "candidates", candidates, ...
    "evidenceTable", evidenceTable, ...
    "csvPath", csvPath, ...
    "summaryPath", summaryPath, ...
    "csvSha256", csvHash, ...
    "summarySha256", summaryHash, ...
    "loadedBlockDiagramsBefore", loadedBefore, ...
    "loadedBlockDiagramsAfter", loadedAfter, ...
    "propertyStateCanonicalCleared", true, ...
    "pathRestored", true, ...
    "warningsRestored", true, ...
    "h1aCandidateBaselineSelectedForExperiment", true, ...
    "h1aCandidateBaselinePromotedToFormalModel", false, ...
    "h1bExecuted", true, ...
    "h1bPressurePathSelectedAsFormal", false, ...
    "modelModified", false, ...
    "formalPropertyModified", false, ...
    "slxLoadedOrSimulated", false, ...
    "authorizesRepair", false, ...
    "formalModelPromotion", false, ...
    "task8Passed", false, ...
    "steady14000AcceptancePassed", false);
end

