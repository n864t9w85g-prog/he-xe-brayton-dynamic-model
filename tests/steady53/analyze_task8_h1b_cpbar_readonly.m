    "h1aCsvSha256", sha256File(config.h1aCsvPath), ...
    "h1aTxtSha256", sha256File(config.h1aTxtPath), ...
    "inputMatSha256", sha256File(config.inputMat), ...
    "modelSha256", sha256File(config.modelPath), ...
    "formalPropertySha256", sha256File(config.formalPropertyPath), ...
    "turbineTableSha256", sha256File(config.turbineTableMat), ...
    "schemeAHelperSha256", sha256File(config.schemeAHelperPath), ...
    "h2aCsvSha256", sha256File(config.h2aCsvPath), ...
    "h2aTxtSha256", sha256File(config.h2aTxtPath));
end

function commit = resolveArchiveCommit(reference)
root = fileparts(fileparts(fileparts(mfilename("fullpath"))));
command = sprintf('git -C "%s" rev-parse ''%s''', root, reference);
[status, output] = system(command);
commit = strtrim(string(output));
if status ~= 0 || isempty(regexp(char(commit), '^[0-9a-f]{40}$', 'once'))
    error("steady53:H1bProtectedHashMismatch", ...
        "Could not resolve the fixed restart archive ref.");
end
end

function evidence = validateH1aEvidence(config, hashes)
try
    csv = readtable(config.h1aCsvPath, "TextType", "string", ...
        "VariableNamingRule", "preserve");
catch exception
    invalid = MException("steady53:H1bInvalidH1aEvidence", ...
        "Approved H1a CSV is not parseable.");
    invalid = addCause(invalid, exception);
    throw(invalid);
end
required = ["method" "phiBar" "T2s_K" "T2_K" "runId" ...
    "inputMat" "inputMatSha256" "formalModel" "modelSha256" ...
    "formalProperty" "formalPropertySha256" "s2PropertySource" ...
    "s2PropertySourceSha256" "s2ApprovedH2aCsv" ...
    "s2ApprovedH2aCsvSha256" "s2ApprovedH2aTxt" ...
    "s2ApprovedH2aTxtSha256" "s2PhiVariant" "s2PhiScope" ...
    "schemeADefinition" "etaCp1Cp2HeldFixed" ...
    "s2IntegrationCompleted" "s2RootConverged" ...
    "s2PathAuditAllPhysical" "s2PathAuditFormalGlobalProof" ...
    "slxLoadedOrSimulated" "h1bExecuted" "authorizesRepair" ...
    "formalModelPromotion"];
methods = ["baseline"; "S1"; "S2_schemeA_phiOnly"];
if height(csv) ~= 3 || ...
        ~all(ismember(required, string(csv.Properties.VariableNames))) || ...
        ~isequal(sort(csv.method), sort(methods)) || ...
        nnz(csv.method == "S2_schemeA_phiOnly") ~= 1
    invalidH1a("H1a CSV rows, methods, or required columns are invalid.");
end
if any(csv.runId ~= config.runId) || ...
        any(csv.inputMat ~= config.inputMat) || ...
        any(csv.inputMatSha256 ~= hashes.inputMatSha256) || ...
        any(csv.formalModel ~= config.modelPath) || ...
        any(csv.modelSha256 ~= hashes.modelSha256) || ...
        any(csv.formalProperty ~= config.formalPropertyPath) || ...
        any(csv.formalPropertySha256 ~= hashes.formalPropertySha256) || ...
        any(csv.s2PropertySource ~= config.schemeAHelperPath) || ...
        any(csv.s2PropertySourceSha256 ~= hashes.schemeAHelperSha256) || ...
        any(csv.s2ApprovedH2aCsv ~= config.h2aCsvPath) || ...
        any(csv.s2ApprovedH2aCsvSha256 ~= hashes.h2aCsvSha256) || ...
        any(csv.s2ApprovedH2aTxt ~= config.h2aTxtPath) || ...
        any(csv.s2ApprovedH2aTxtSha256 ~= hashes.h2aTxtSha256)
    invalidH1a("H1a CSV dependency identities are invalid.");
end
if any(csv.s2PhiVariant ~= "schemeA") || ...
        any(csv.s2PhiScope ~= "only H1a-S2 phi integrand") || ...
        any(csv.schemeADefinition ~= ...
        "ignoreHePureThirdVirialBeforeCurrentMixingRule") || ...
        ~all(csv.etaCp1Cp2HeldFixed) || ...
        ~all(csv.s2IntegrationCompleted) || ~all(csv.s2RootConverged) || ...
        ~all(csv.s2PathAuditAllPhysical) || ...
        any(csv.s2PathAuditFormalGlobalProof) || ...
        any(csv.slxLoadedOrSimulated) || any(csv.h1bExecuted) || ...
        any(csv.authorizesRepair) || any(csv.formalModelPromotion)
    invalidH1a("H1a CSV scope or status boundaries are invalid.");
end
row = csv(csv.method == "S2_schemeA_phiOnly", :);
baselineRow = csv(csv.method == "baseline", :);
if ~near(row.phiBar, 0.39979002315209694, 1e-15) || ...
        ~near(row.T2s_K, 1089.5635709913104, 1e-12) || ...
        ~near(row.T2_K, 1143.6624955393854, 1e-9) || ...
        ~near(baselineRow.T2s_K, 1089.6475181122112, 1e-9)
    invalidH1a("H1a-S2 fixed numerical baseline is invalid.");
end
evidence = struct("phiBar", 0.39979002315209694, ...
    "T2s_K", 1089.5635709913104, "T2_K", 1143.6624955393854, ...
    "pointCp2SourceT_K", 1089.6475181122112);
end

