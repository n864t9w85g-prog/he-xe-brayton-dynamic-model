function valid = near(actual, expected, tolerance)
valid = finiteRealScalar(actual) && abs(double(actual)-expected) <= tolerance;
end

function inputs = validateAndExtractPayload(payload, expectedModelHash)
if ~isstruct(payload) || ~all(isfield(payload, ...
        ["result" "report" "spec"])) || ...
        ~isstruct(payload.result) || ~isstruct(payload.report) || ...
        ~isstruct(payload.spec)
    invalidInput("Missing result, report, or spec payload.");
end
result = payload.result;
report = payload.report;
spec = payload.spec;
if ~all(isfield(result, ["t" "signals" "modelHashBefore" ...
        "modelHashAfter"])) || ~isstruct(result.signals)
    invalidInput("Missing required result fields.");
end
t = double(result.t(:));
if numel(t) < 2 || any(~isfinite(t)) || any(diff(t) <= 0) || ...
        ~isfield(spec, "finalWindow_s") || numel(spec.finalWindow_s) ~= 2
    invalidInput("Recorded time or final-window evidence is invalid.");
end
window = double(spec.finalWindow_s(:));
if any(~isfinite(window)) || window(1) >= window(2) || ...
        window(1) < t(1) || window(2) > t(end) || ...
        nnz(t >= window(1) & t <= window(2)) < 2
    invalidInput("The final window is outside recorded coverage.");
end
if lower(string(result.modelHashBefore)) ~= expectedModelHash || ...
        lower(string(result.modelHashAfter)) ~= expectedModelHash
    invalidInput("Recorded model hashes do not match the protected model.");
end
requiredSignals = ["turbine_inlet_T" "turbine_inlet_P" ...
    "turbine_outlet_P" "turbine_outlet_T" ...
    "turbine_lookup_mass_flow" "turbine_lookup_speed_eff"];
for signal = requiredSignals
    if ~isfield(result.signals, signal)
        invalidInput("A required turbine signal is missing.");
    end
    values = result.signals.(signal);
    if ~isnumeric(values) || ~isvector(values) || numel(values) ~= numel(t) || ...
            ~isreal(values) || any(~isfinite(values))
        invalidInput("A required turbine signal is invalid.");
    end
end
if ~isfield(report, "metrics") || ~istable(report.metrics) || ...
        ~all(ismember(["metricName" "target"], ...
        string(report.metrics.Properties.VariableNames)))
    invalidInput("Report metrics are invalid.");
end
targetRow = string(report.metrics.metricName) == "turbine_outlet_T";
if nnz(targetRow) ~= 1 || ...
        ~finiteRealScalar(report.metrics.target(targetRow))
    invalidInput("The turbine outlet target is invalid.");
end
last = @(name) double(result.signals.(name)(end));
inputs = struct( ...
    "T1_K", last("turbine_inlet_T"), ...
    "P1_Pa", last("turbine_inlet_P"), ...
    "P2_Pa", last("turbine_outlet_P"), ...
    "recordedTerminalT2_K", last("turbine_outlet_T"), ...
    "lookupMassFlow_kg_s", last("turbine_lookup_mass_flow"), ...
    "lookupSpeed_rpm", last("turbine_lookup_speed_eff"), ...
    "targetT2_K", double(report.metrics.target(targetRow)), ...
    "tFinal_s", t(end), ...
    "finalWindow_s", window.');
scalarValues = [inputs.T1_K inputs.P1_Pa inputs.P2_Pa ...
    inputs.recordedTerminalT2_K inputs.lookupMassFlow_kg_s ...
    inputs.lookupSpeed_rpm inputs.targetT2_K];
if any(~isfinite(scalarValues)) || any(scalarValues <= 0)
    invalidInput("A terminal turbine value is outside its physical domain.");
end
end

