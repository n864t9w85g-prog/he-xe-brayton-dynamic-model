function [csvHash, summaryHash] = publishEvidence( ...
        outputDir, evidenceTable, summaryText, outputFailureHook)
[outputParent, outputName, outputExtension] = fileparts(outputDir);
outputParent = string(outputParent);
outputLeaf = string(outputName)+string(outputExtension);
if isfile(outputParent)
    error("steady53:H1bOutputFailed", ...
        "The H1b output parent exists as a non-directory.");
end
if ~isfolder(outputParent)
    [created, message] = mkdir(outputParent);
    if ~created || ~isfolder(outputParent)
        error("steady53:H1bOutputFailed", ...
            "Could not create H1b output parent: %s", message);
    end
end
if isfolder(outputDir) || isfile(outputDir)
    error("steady53:H1bOutputExists", ...
        "H1b output target already exists: '%s'.", outputDir);
end

stagingPrefix = "."+outputLeaf+".staging_";
[~, uniqueLeaf] = fileparts(tempname(outputParent));
stagingDir = string(fullfile(outputParent, ...
    stagingPrefix+string(uniqueLeaf)));
try
    [created, message] = mkdir(stagingDir);
    if ~created || ~isfolder(stagingDir)
        error("steady53:H1bOutputFailed", ...
            "Could not create H1b staging directory: %s", message);
    end
    stagingCleanup = onCleanup(@() cleanupStaging( ...
        stagingDir, outputParent, stagingPrefix));
    stagedCsv = fullfile(stagingDir, "h1b_cpbar_sensitivity.csv");
    stagedTxt = fullfile(stagingDir, "h1b_cpbar_summary.txt");
    writetable(evidenceTable, stagedCsv);
    outputFailureHook("afterCsvBeforeSummary", stagingDir);
    writeUtf8Text(stagedTxt, summaryText);
    validateStagedEvidence(stagedCsv, stagedTxt);
    csvHash = sha256File(stagedCsv);
    summaryHash = sha256File(stagedTxt);
    if isfolder(outputDir) || isfile(outputDir)
        error("steady53:H1bOutputExists", ...
            "H1b output target appeared before publication.");
    end
    outputFailureHook("beforePublish", stagingDir);
    moveDirectoryNoReplace(stagingDir, outputDir);
    if sha256File(fullfile(outputDir, "h1b_cpbar_sensitivity.csv")) ~= ...
            csvHash || ...
            sha256File(fullfile(outputDir, "h1b_cpbar_summary.txt")) ~= ...
            summaryHash
        cleanupPublished(outputDir, outputParent, outputLeaf);
        error("steady53:H1bOutputFailed", ...
            "Published H1b hashes differ from staged hashes.");
    end
    clear stagingCleanup
catch exception
    if exist("stagingDir", "var")
        cleanupStaging(stagingDir, outputParent, stagingPrefix);
    end
    if exception.identifier == "steady53:H1bOutputExists"
        rethrow(exception);
    end
    failure = MException("steady53:H1bOutputFailed", ...
        "Transactional H1b evidence publication failed.");
    failure = addCause(failure, exception);
    throw(failure);
end
end

function writeUtf8Text(filePath, text)
[fileId, message] = fopen(filePath, "w", "native", "UTF-8");
if fileId < 0
    error("steady53:H1bOutputFailed", ...
        "Could not create staged H1b summary: %s", message);
end
try
    fprintf(fileId, "%s", text);
catch exception
    fclose(fileId);
    rethrow(exception);
end
status = fclose(fileId);
if status ~= 0
    error("steady53:H1bOutputFailed", ...
        "Could not close staged H1b summary.");
end
end

function validateStagedEvidence(csvPath, txtPath)
csv = readtable(csvPath, "TextType", "string", ...
    "VariableNamingRule", "preserve");
summary = string(fileread(txtPath));
expectedMethods = sort([ ...
    "H1a_S2_schemeA_pointCp_baseline"
    "H1b_linearEndpointPressure"
    "H1b_constantP1"
    "H1b_constantP2"]);
if height(csv) ~= 4 || ~isequal(sort(csv.method), expectedMethods) || ...
        ~contains(summary, "h1bPressurePathSelectedAsFormal=false") || ...
        ~contains(summary, "slxLoadedOrSimulated=false")
    error("steady53:H1bOutputFailed", ...
        "Staged H1b evidence is incomplete or not self-consistent.");
end
end

function moveDirectoryNoReplace(stagingDir, outputDir)
sourcePath = javaObject("java.io.File", char(stagingDir)).toPath();
targetPath = javaObject("java.io.File", char(outputDir)).toPath();
noReplaceOptions = javaArray("java.nio.file.CopyOption", 0);
try
    javaMethod("move", "java.nio.file.Files", ...
        sourcePath, targetPath, noReplaceOptions);
catch exception
    if isfolder(outputDir) || isfile(outputDir)
        collision = MException("steady53:H1bOutputExists", ...
            "H1b publication refused to overwrite the target.");
        collision = addCause(collision, exception);
        throw(collision);
    end
    rethrow(exception);
end
end

function cleanupStaging(stagingDir, expectedParent, expectedPrefix)
if ~isfolder(stagingDir)
    return
end
[actualParent, actualName, actualExtension] = fileparts(stagingDir);
actualLeaf = string(actualName)+string(actualExtension);
if string(actualParent) == expectedParent && ...
        startsWith(actualLeaf, expectedPrefix) && ...
        strlength(actualLeaf) > strlength(expectedPrefix)
    rmdir(stagingDir, "s");
end
end

function cleanupPublished(outputDir, expectedParent, expectedLeaf)
if ~isfolder(outputDir)
    return
end
[actualParent, actualName, actualExtension] = fileparts(outputDir);
actualLeaf = string(actualName)+string(actualExtension);
if string(actualParent) == expectedParent && actualLeaf == expectedLeaf
    rmdir(outputDir, "s");
end
end

