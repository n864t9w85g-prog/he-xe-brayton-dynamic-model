function hashValue = sha256File(filePath)
if ~isfile(filePath)
    error("steady53:H1bProtectedHashMismatch", ...
        "Required protected file does not exist: '%s'.", filePath);
end
digest = java.security.MessageDigest.getInstance("SHA-256");
fileBytes = java.nio.file.Files.readAllBytes( ...
    java.io.File(char(filePath)).toPath());
bytes = typecast(digest.digest(fileBytes), "uint8");
hashValue = lower(join(compose("%02x", bytes), ""));
end
