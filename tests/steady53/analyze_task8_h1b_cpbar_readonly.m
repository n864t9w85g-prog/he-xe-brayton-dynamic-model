function config = applyOptions(config, options)
if ~isstruct(options) || ~isscalar(options) || ...
        ~isfield(options, "testOnly") || ~isequal(options.testOnly, true)
    invalidOptions("Non-default options require testOnly=true.");
end
actual = sort(string(fieldnames(options)));
convenience = sort(["testOnly"; "outputDir"]);
controlled = sort(["testOnly"; "testControl"]);
if isequal(actual, convenience)
    outputDir = string(options.outputDir);
    if ~isscalar(outputDir) || ismissing(outputDir) || ...
            strlength(outputDir) == 0 || ~startsWith(outputDir, filesep)
        invalidOptions("The test outputDir must be an absolute path.");
    end
    config.outputDir = outputDir;
elseif isequal(actual, controlled)
    control = options.testControl;
    if ~isstruct(control) || ~isscalar(control) || ...
            ~isequal(sort(string(fieldnames(control))), ...
            sort(string(fieldnames(config))))
        invalidOptions("testControl must state the exact complete contract.");
    end
    config = control;
else
    invalidOptions("Unknown or partial H1b test-only options.");
end
end

function validateConfig(config)
pathFields = ["inputMat" "modelPath" "formalPropertyPath" ...
    "turbineTableMat" "schemeAHelperPath" "h1aCsvPath" ...
    "h1aTxtPath" "h2aCsvPath" "h2aTxtPath" "outputDir"];
for field = pathFields
    value = string(config.(field));
    if ~isscalar(value) || ismissing(value) || strlength(value) == 0 || ...
            ~startsWith(value, filesep)
        invalidOptions(field+" must be an absolute path.");
    end
    config.(field) = value;
end
hashFields = ["expectedInputSha256" "expectedModelSha256" ...
    "expectedFormalPropertySha256" "expectedTurbineTableSha256" ...
    "expectedSchemeAHelperSha256" "expectedH1aCsvSha256" ...
    "expectedH1aTxtSha256" "expectedH2aCsvSha256" ...
    "expectedH2aTxtSha256"];
for field = hashFields
    value = string(config.(field));
    if ~isscalar(value) || isempty(regexp(char(value), ...
            '^[0-9a-fA-F]{64}$', 'once'))
        invalidOptions(field+" must be a SHA-256 value.");
    end
end
if config.runId ~= ...
        "run_1787582761047_bb4aa60600cc4d9e9cc15077c6f435d3" || ...
        config.archiveRef ~= "archive/pre-restart-20260824^{}" || ...
        config.expectedArchiveCommit ~= ...
        "8f625c268c35a95c18a626305c1aa6a79ae2ace7" || ...
        ~isa(config.propertyFunction, "function_handle") || ...
        ~isa(config.outputFailureHook, "function_handle") || ...
        ~isequal(config.pathVariants, ...
        ["linearEndpointPressure" "constantP1" "constantP2"])
    invalidOptions("The fixed H1b identity or function contract is invalid.");
end
end

