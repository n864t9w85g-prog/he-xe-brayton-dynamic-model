function yes = mappingApiEvidenceComplete(mapping)
if any(strlength(string(mapping.traced_signal_paths)) == 0)
    yes = false;
    return
end
if string(mapping.power_definition) == "electrical_paper_eta"
    yes = string(mapping.api_verification_status) == ...
        "verified_offline_composition_of_api_traces" && ...
        ~mapping.direct_model_endpoint_claimed && ...
        isempty(mapping.api_trace_records) && ...
        isequal(sort(string(mapping.composition_sources)), ...
            sort(["turbine"; "compressor"]));
    return
end
records = mapping.api_trace_records;
yes = string(mapping.api_verification_status) == ...
    "verified_by_official_api_graph" && mapping.direct_model_endpoint_claimed && ...
    numel(records) == numel(mapping.traced_state_paths) && ~isempty(records);
for index = 1:numel(records)
    hops = records(index).hops;
    yes = yes && string(records(index).status) == ...
        "verified_by_official_api_graph" && ~isempty(hops) && ...
        string(hops(1).from_block) == string(records(index).state_path) && ...
        string(hops(end).to_block) == string(records(index).endpoint_block) && ...
        hops(end).to_port == records(index).endpoint_port && ...
        string(hops(end).to_port_kind) == ...
            string(records(index).endpoint_port_kind) && ...
        all(ismember(string({hops.bridge_kind}), ...
            ["signal_line", "subsystem_inport", "subsystem_outport", ...
             "goto_from", "block_dependency"]));
end
end

