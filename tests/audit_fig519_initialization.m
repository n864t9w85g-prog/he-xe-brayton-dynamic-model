function explanation = explainFlatStart( ...
        inventory, runResult, powerPaths, traceContract)
t = double(runResult.t(:));
signals = runResult.signals;
reactor = double(signals.reactor_power(:));
turbine = double(signals.turbine_power(:));
compressor = double(signals.compressor_power(:));
electrical = 0.98 .* (turbine - compressor);
definitions = [ ...
    powerEvidence("reactor", "P_sw", powerPaths.reactor.upstream_block, t, reactor); ...
    powerEvidence("turbine", "WT_sw", powerPaths.turbine.block, t, turbine); ...
    powerEvidence("compressor", "Wc_sw", powerPaths.compressor.block, t, compressor); ...
    powerEvidence("electrical_paper_eta", "0.98*(WT_sw-Wc_sw)", ...
        "offline derivation from verified turbine/compressor paths", t, electrical)];
threshold = 1e-6;
stateEvidence = repmat(struct("path", "", "first_sample_slope", NaN, ...
    "normalized_first_sample_slope_per_s", NaN, ...
    "near_zero_by_rule", false, "absolute_change_500s", NaN), ...
    numel(inventory), 1);
for index = 1:numel(inventory)
    stateEvidence(index).path = inventory(index).path;
    stateEvidence(index).first_sample_slope = inventory(index).first_sample_slope;
    stateEvidence(index).normalized_first_sample_slope_per_s = ...
        abs(inventory(index).first_sample_slope) / ...
        max(abs(inventory(index).t0_value), 1);
    stateEvidence(index).near_zero_by_rule = ...
        stateEvidence(index).normalized_first_sample_slope_per_s <= threshold;
    stateEvidence(index).absolute_change_500s = inventory(index).absolute_change;
end
nearZero = stateEvidence([stateEvidence.near_zero_by_rule]);
model = "final_steady_24a";
reactorStates = string({traceContract.reactor.state_path})';
turbineStates = string({traceContract.turbine.state_path})';
compressorStates = string({traceContract.compressor.state_path})';
electricalStates = unique([turbineStates; compressorStates], "stable");
mappings = [ ...
    powerMapping("reactor", reactorStates, ...
        [string(powerPaths.reactor.upstream_block); ...
         string(powerPaths.reactor.workspace_block)], ...
        "Only recorded reactor states with an official-API graph path to the P_sw logger are listed.", ...
        "verified_by_official_api_graph", traceContract.reactor, true, strings(0, 1)); ...
    powerMapping("turbine", turbineStates, ...
        [string(powerPaths.turbine.block) + " output 4"; ...
         model + "/TAC/WT_sw"], ...
        "Only recorded states with an official-API graph path to the Turbine component are listed.", ...
        "verified_by_official_api_graph", traceContract.turbine, true, strings(0, 1)); ...
    powerMapping("compressor", compressorStates, ...
        [string(powerPaths.compressor.block) + " output 2"; ...
         model + "/TAC/Wc_sw"], ...
        "Only recorded states with an official-API graph path to the Compressor component are listed.", ...
        "verified_by_official_api_graph", traceContract.compressor, true, strings(0, 1)); ...
    powerMapping("electrical_paper_eta", electricalStates, ...
        [string(powerPaths.turbine.block) + " output 4"; model + "/TAC/WT_sw"; ...
         string(powerPaths.compressor.block) + " output 2"; model + "/TAC/Wc_sw"], ...
        "The electrical definition is only an offline composition of the two API-verified shaft paths; no direct model endpoint is claimed.", ...
        "verified_offline_composition_of_api_traces", emptyTraceRecord(), false, ...
        ["turbine"; "compressor"])];
nearZeroPaths = string({nearZero.path});
mappingStateComplete = numel(mappings) == 4 && all(arrayfun(@(item) ...
    ~isempty(item.traced_state_paths) && ...
    all(ismember(string(item.traced_state_paths), nearZeroPaths)), mappings));
mappingSignalComplete = all(arrayfun(@(item) ...
    mappingApiEvidenceComplete(item), mappings));
explanation = struct( ...
